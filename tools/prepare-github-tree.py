"""Extract the six-flower source ZIP into a clean GitHub upload tree; no push."""
from pathlib import Path
import json,zipfile,hashlib,shutil,sys
OUT=(Path(sys.argv[1]) if len(sys.argv)>1 else Path(__file__).resolve().parents[2]/'particle-bloom-release').resolve()
archive=OUT/'particle-bloom-sixflowers-source.zip';target=(OUT/'github-ready').resolve()
if target.parent!=OUT or target.name!='github-ready':raise SystemExit('Upload tree must stay inside the output directory.')
if target.exists():
    previous=OUT/'GITHUB-UPLOAD-MANIFEST.json'
    if not previous.is_file():raise SystemExit('Existing github-ready directory is not a verified generated tree; move it yourself first.')
    prior=json.loads(previous.read_text(encoding='utf-8'))
    known={item['path'] for items in prior['groups'].values() for item in items}
    actual={p.relative_to(target).as_posix() for p in target.rglob('*') if p.is_file()}
    if prior.get('tree') not in ('github-ready',str(target)) or actual-known:raise SystemExit('Existing tree contains unexpected files; refusing to replace it.')
    shutil.rmtree(target)
target.mkdir(parents=True)
with zipfile.ZipFile(archive) as z:
    for entry in z.infolist():
        relative=Path(entry.filename).relative_to('particle-bloom-source')
        if '..' in relative.parts or relative.is_absolute():raise ValueError('Unsafe archive path')
        file=target/relative;file.parent.mkdir(parents=True,exist_ok=True);file.write_bytes(z.read(entry))
files=[];groups={}
for p in sorted(target.rglob('*')):
    if p.is_file():
        name=p.relative_to(target).as_posix();item={'path':name,'bytes':p.stat().st_size,'sha256':hashlib.sha256(p.read_bytes()).hexdigest()}
        if item['bytes']>25_000_000:raise ValueError(f'File exceeds browser upload budget: {name}')
        files.append(item);groups.setdefault(str(Path(name).parent),[]).append(item)
report={'tree':'github-ready','file_count':len(files),'total_bytes':sum(f['bytes'] for f in files),'largest_file':max(files,key=lambda f:f['bytes']),'groups':groups,'excluded':['.git','.openai','node_modules','.env*','private reference image'],'publication_performed':False}
(OUT/'GITHUB-UPLOAD-MANIFEST.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
lines=['GitHub-ready six-flower source upload manifest','Generated by tools/prepare-github-tree.py from particle-bloom-sixflowers-source.zip.','Archive prefix particle-bloom-source/ is extracted into github-ready/.','No publication performed. Do not upload before the authorized time.','',f'Files: {len(files)}; total bytes: {report["total_bytes"]}; every file < 25 MB','']
for directory,items in groups.items():
    lines.append(f'[{directory}] ({sum(f["bytes"] for f in items):,} bytes)')
    for f in items:lines.append(f'  {f["path"]}  {f["bytes"]:,} bytes')
    lines.append('')
lines+=['Optional root/download assets (outside source tree):','  particle-bloom-sixflowers-source.zip','  particle-bloom-sixflowers-windows-ready.zip','','Excluded: .git, .openai/Site identity, node_modules, .env*, original reference-person image.']
(OUT/'GITHUB-UPLOAD-MANIFEST.txt').write_text('\n'.join(lines)+'\n',encoding='utf-8')
print(json.dumps({**{k:v for k,v in report.items() if k!='groups'},'tree':str(target)},ensure_ascii=False,indent=2))
